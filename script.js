// Trigger the evidence bar chart animation only once it scrolls into view
const evidenceChart = document.querySelector(".evidence-chart");
if (evidenceChart && "IntersectionObserver" in window) {
  const chartObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        evidenceChart.classList.add("in-view");
        chartObserver.unobserve(entry.target);
      }
    });
  }, { threshold: 0.4 });
  chartObserver.observe(evidenceChart);
} else if (evidenceChart) {
  evidenceChart.classList.add("in-view");
}


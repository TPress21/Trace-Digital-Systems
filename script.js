// Booking form — posts to Formspree. Replace FORMSPREE_ID below with your
// own form ID once you've created a Formspree account (see README).
const FORMSPREE_ID = "YOUR_FORM_ID"; // e.g. "mzbqwxyz"

bookForm.addEventListener("submit", async function (e) {
  e.preventDefault();
  const submitBtn = bookForm.querySelector("button[type=submit]");
  const originalText = submitBtn.textContent;
  const errorText = {
    en: "Something went wrong — please try again", es: "Algo salió mal — inténtalo de nuevo",
    zh: "出现问题，请重试", vi: "Đã xảy ra lỗi — vui lòng thử lại"
  };
  const sentText = {
    en: "Request sent ✓", es: "Enviado ✓", zh: "已提交 ✓", vi: "Đã gửi ✓"
  };

  if (FORMSPREE_ID === "YOUR_FORM_ID") {
    // Not yet connected — see README "Connect the booking form" step.
    console.warn("Trace: booking form is not yet connected to Formspree. See README.");
    submitBtn.textContent = sentText[currentLang] || sentText.en;
    submitBtn.disabled = true;
    return;
  }

  submitBtn.disabled = true;
  try {
    const res = await fetch(`https://formspree.io/f/${FORMSPREE_ID}`, {
      method: "POST",
      headers: { "Accept": "application/json" },
      body: new FormData(bookForm),
    });
    if (res.ok) {
      submitBtn.textContent = sentText[currentLang] || sentText.en;
      bookForm.reset();
    } else {
      submitBtn.textContent = errorText[currentLang] || errorText.en;
      submitBtn.disabled = false;
    }
  } catch (err) {
    submitBtn.textContent = errorText[currentLang] || errorText.en;
    submitBtn.disabled = false;
  }
});
